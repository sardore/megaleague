import { build } from 'esbuild';
import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import http from 'node:http';
const bundle=await build({entryPoints:['tests/helpers/zombie-probe.js'],bundle:true,write:false,outdir:'probe',loader:{'.css':'empty'},format:'iife'});
const html=(await fs.readFile('index.html','utf8')).replace(/<script[^>]+src="[^"]+"[^>]*><\/script>/,'<script src="/probe.js"></script>');
const server=http.createServer(async(req,res)=>{if(req.url==='/probe.js'){res.setHeader('Content-Type','text/javascript');res.end(bundle.outputFiles[0].text);return;}if(req.url==='/'){res.end(html);return;}try{res.end(await fs.readFile('.'+req.url.split('?')[0]));}catch{res.statusCode=404;res.end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const b=await chromium.launch();const p=await b.newPage();
await p.goto(`http://127.0.0.1:${server.address().port}`);await p.waitForFunction(()=>window.zombieFixture);
const r=await p.evaluate(()=>{const out={};for(const d of [1,2,3,4,5,7,9,12]){const g=zombieFixture('share'+d);const c=g.bossRaid.cave;c.depth=d;c.region='sewer';let n=0;for(let i=0;i<1500;i++){c.serial=i;if(probe.zc.pickZombieId(g).startsWith('zp:'))n++;}out[d]=Math.round(n/15)/1;}return out;});
console.log(JSON.stringify(r));
await b.close();server.close();
